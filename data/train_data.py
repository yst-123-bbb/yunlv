def get_train_backup(departure, destination):
    """获取高铁方案 - 12306风格

    返回: 车次列表，每车次含:
    train_no, dep_station, arr_station,
    dep_time, arr_time, duration,
    seats(二等座/一等座/商务座/特等座)
    """
    k1 = departure + "-" + destination
    k2 = destination + "-" + departure

    if k1 in _PAIRS:
        raw = _PAIRS[k1]
    elif k2 in _PAIRS:
        raw = _PAIRS[k2]
    else:
        raw = []
        for i in range(6):
            h1 = 7 + i * 2
            h2 = h1 + 5
            raw.append(("G" + str(301 + i * 17),
                     departure + "站",
                     destination + "站",
                     str(h1).zfill(2) + ":00",
                     str(h2).zfill(2) + ":30",
                     "5小时" + str(30 + i * 5) + "分",
                     400 + i * 80, 700 + i * 100))

    trains = []
    for r in raw:
        try:
            no, ds, ast, dt, at, dur, p2, p1 = r
            trains.append({
                "train_no": no,
                "dep_station": ds,
                "arr_station": ast,
                "dep_time": dt,
                "arr_time": at,
                "duration": dur,
                "seats": {
                    "二等座": p2,
                    "一等座": p1,
                    "商务座": int(p1 * 1.8),
                    "特等座": int(p1 * 2.2),
                },
                "train_type": "高速动车",
                "from_city": departure,
                "to_city": destination,
                "has_wifi": "有WiFi",
                "has_power": "有充电插座",
                "has_meal": "提供餐饮",
            })
        except Exception:
            continue

    if trains:
        trains[0]["_tag"] = "推荐"
        if len(trains) >= 3:
            trains[len(trains) // 2]["_tag"] = "价格最低"
    return trains


