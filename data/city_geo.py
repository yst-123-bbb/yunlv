_EARTH_RADIUS_KM = 6371.0

_PROVINCE_BY_CITY: dict[str, str] = {city["name"]: city["province"] for city in CITIES}


def province_of(city: str) -> str:
    """返回城市所属省级行政区，未收录的城市返回空串。"""
    return _PROVINCE_BY_CITY.get(city, "")


def distance_km(a: str, b: str) -> float:
    """两城球面距离（km）；任一城市缺坐标时返回 -1.0。"""
    coord_a = CITY_COORDS.get(a)
    coord_b = CITY_COORDS.get(b)
    if coord_a is None or coord_b is None:
        return -1.0

    lat1, lon1 = coord_a
    lat2, lon2 = coord_b
    phi1 = math.radians(lat1)
    phi2 = math.radians(lat2)
    d_phi = phi2 - phi1
    d_lambda = math.radians(lon2 - lon1)
    h = math.sin(d_phi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(d_lambda / 2) ** 2
    return 2 * _EARTH_RADIUS_KM * math.asin(math.sqrt(h))